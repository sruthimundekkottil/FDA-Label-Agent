"""Draw the agent graph from its real wiring.

    python -m agent.draw_graph                       # docs/agent_graph.md (Mermaid, offline)
    python -m agent.draw_graph --png docs/agent_graph.png

The Mermaid text comes from ``graph.get_graph().draw_mermaid()``, so the diagram
can never drift from the code. ``--png`` renders it through the public
mermaid.ink service (LangGraph's default): only the diagram text is sent.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from agent.llm.mock import MockAdapter
from agent.loop import AgentGraph
from agent.tools import ToolBox

DEFAULT_OUT = Path("docs/agent_graph.md")


def build_mermaid() -> str:
    # The wiring does not depend on the model or the indexes, so nothing heavy loads here.
    graph = AgentGraph(llm=MockAdapter(), toolbox=ToolBox(drugs=["placeholder"]))
    return graph.mermaid()


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=str(DEFAULT_OUT), help="markdown file with a mermaid block")
    parser.add_argument("--png", default=None, help="also render a PNG via mermaid.ink (network)")
    parser.add_argument("--print", action="store_true", help="print the Mermaid text")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    mermaid = build_mermaid()
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "# Agent graph\n\nGenerated by `python -m agent.draw_graph` from the compiled LangGraph.\n\n"
        f"```mermaid\n{mermaid}```\n",
        encoding="utf-8",
    )
    print(f"wrote {out}")
    if args.print:
        print(mermaid)
    if args.png:
        graph = AgentGraph(llm=MockAdapter(), toolbox=ToolBox(drugs=["placeholder"]))
        Path(args.png).parent.mkdir(parents=True, exist_ok=True)
        graph.graph.get_graph().draw_mermaid_png(output_file_path=args.png)
        print(f"wrote {args.png}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
